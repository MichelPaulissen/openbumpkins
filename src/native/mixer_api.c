void *bb_mixer_resource(const char *name, const char *type, U32 *size) {
  const void *data = NULL;
  U32 length = 0;
  if ((uintptr_t)type == 6 && (uintptr_t)name == 1) {
    data = &strings_1;
    length = sizeof(strings_1);
  }
  if ((uintptr_t)type == 6 && (uintptr_t)name == 2) {
    data = &strings_2;
    length = sizeof(strings_2);
  }
  if ((uintptr_t)type == 6 && (uintptr_t)name == 3) {
    data = &strings_3;
    length = sizeof(strings_3);
  }
  if ((uintptr_t)type == 16 && (uintptr_t)name == 1) {
    data = &version_info;
    length = sizeof(version_info);
  }
  if (data && size)
    *size = length;
  return (void *)(uintptr_t)data;
}
