static uint16_t strings_1[1032 / 2], strings_2[1392 / 2], strings_3[160 / 2];

void bb_mixer_initialize_resources(void) {
  uint16_t *blocks[] = {strings_1, strings_2, strings_3};
  for (unsigned block = 0; block < 3; ++block) {
    uint16_t *out = blocks[block];
    for (unsigned entry = 0; entry < 16; ++entry) {
      const uint_least16_t *text = messages[block * 16 + entry];
      unsigned length = 0;
      while (text[length])
        ++length;
      *out++ = length;
      memcpy(out, text, length * sizeof(*out));
      out += length;
    }
  }
}

