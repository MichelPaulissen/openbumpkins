/* Resource order, destination slots and post-load anchors retain their original
 * order. Blank surfaces share the same declarations with their width/height. */
static void load_assets(const struct startup_asset *assets, size_t count,
                        int samples) {
  for (size_t i = 0; i < count; ++i) {
    const struct startup_asset *a = assets + i;
    uint32_t object;
    if (samples)
      object = bb_address_encode(bb_audio_resource_create_entry(
          PTR(0x005590e8), TEXT(a->name), a->options));
    else if (a->post == 4)
      object = M3(0x0042f2c0, DISPLAY, a->name, a->x, a->options);
    else
      object = M2(0x0042f320, DISPLAY, a->name, a->options);
    BB_U32(a->slot) = object;
    switch (a->post) {
    case 1:
      M0(0x0042f7a0, object);
      break;
    case 2:
      M2(0x0042f780, object, a->x, a->y);
      break;
    case 3:
      BB_U32(object + 0x54) = 0u - BB_U32(object + 0x54);
      break;
    }
  }
}
