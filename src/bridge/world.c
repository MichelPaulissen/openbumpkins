/* 0040cfa0: copy the full 914-byte type record in forward word order. The
 * source's counter is reset after copying, including when both types alias. */
void bb_type_clone_entry(uint32_t source, uint32_t destination) {
  uintptr_t src = 0x00663538 + (uint8_t)source * 914u;
  uintptr_t dst = 0x00663538 + (uint8_t)destination * 914u;
  for (unsigned i = 0; i < 912; i += 4)
    BB_U32(dst + i) = BB_U32(src + i);
  WORD(dst + 912) = WORD(src + 912);
  BYTE(dst + 0x84) = (uint8_t)source;
  WORD(src + 0x380) = 0;
  BB_U32(dst + 0x62) = 0;
  BB_U32(dst + 0x66) = 0;
  BB_U32(dst + 0x40) = 0;
}

/* 004293e0: two flag planes from an 11x11 blueprint. Zero bits leave the
 * existing planes alone; the planes have different row strides. */
void bb_type_blueprint_entry(uint32_t type, const uint8_t *cells) {
  uintptr_t flags = 0x00663688 + (uint8_t)type * 914u;
  uintptr_t occupancy = 0x00663584 + (uint8_t)type * 914u;
  for (unsigned row = 0; row < 11; ++row)
    for (unsigned col = 0; col < 11; ++col) {
      uintptr_t cell = (uintptr_t)cells + row * 11u + col;
      if (BYTE(cell) & 1)
        BB_U32(flags + (row * 11u + col) * 4u) = 1;
      if (BYTE(cell) & 2)
        BB_U32(occupancy + row * 28u + col * 4u) = 1;
    }
}

