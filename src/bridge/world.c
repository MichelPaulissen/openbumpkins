static uint32_t localized_copy(char *out, const char *text) {
  if (!text)
    text = (const char *)0x0048481c;
  uint32_t length = (uint32_t)strlen(BB_DATA(text)) + 1, left = length;
  while (left >= 4) {
    BB_U32(out) = BB_U32(text);
    out += 4;
    text += 4;
    left -= 4;
  }
  while (left--)
    BYTE(out++) = BYTE(text++);
  return length;
}
