/* 0040d020: initialize game type data, UI records, palettes and world terrain.
 * Default records are C data, with ordinary loops and explicit helper calls. */
void bb_world_initialize_entry(void) {
  initialize_interface_records();
  initialize_world_tables();
  initialize_type_names();
  initialize_type_defaults();
  initialize_geometry_tables();
  initialize_prices_and_terrain();
  bb_terrain_prepare_entry();
  bb_icon_panel_initialize_entry((void *)0x005ca308);
  bb_build_menu_initialize_entry((void *)0x005f90d8);
  bb_worker_menu_initialize_entry((void *)0x006a98e0);
  bb_cursor_initialize_entry((void *)0x006b0830);
  bb_entity_project((void *)0x00553f90, 0, 0x04000000);
  for (unsigned i = 0; i < 64; ++i) {
    long double exponent =
        (long double)i * BB_DOUBLE(0x00482178) + BB_DOUBLE(0x00482180);
    long double power = powl(BB_DOUBLE(0x00482170), exponent);
    /* The remaining game CRT shares its last intrinsic result and validity
     * byte with later math calls. Keep that bridge state until it is retired.
     */
    BB_DOUBLE(0x006c8890) = (double)power;
    BYTE(0x006c8898) = 1;
    long double value = sinl((long double)i) * power;
    BB_U32(0x005fe298 + i * 4u) = (uint32_t)(int64_t)value;
  }
  static const uint8_t colors[] = {124, 4, 39, 139, 180};
  for (unsigned player = 0; player < 5; ++player)
    for (unsigned i = 0; i < 4; ++i)
      BYTE(0x006045f8 + player * 4u + i) =
          (uint8_t)(colors[player] + bb_random() % 3 - 1);
}
