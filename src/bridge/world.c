/* Distance/direction caches and circular placement offsets retain their
 * integer results. Intermediate calculations are extended C arithmetic. */
static void initialize_geometry_tables(void) {
  WORD(0x0068cd3a) = 0;
  WORD(0x0068d0cc) = 0;
  WORD(0x0068db82) = 0;

  for (int32_t y = -32; y < 32; ++y)
    for (int32_t x = -32; x < 32; ++x) {
      int32_t index = y * 64 + x;
      if (!x && !y) {
        BB_U32(0x005fb2f0) = 0;
        BYTE(0x005fda98) = 0;
      } else {
        long double distance =
            sqrtl((long double)(x * x + y * y)) * BB_DOUBLE(0x00482148);
        BB_U32(0x005fb2f0 + index * 4) = (uint32_t)(int64_t)distance;
        BYTE(0x005fda98 + index) = bb_direction_entry(x, y);
      }
    }
  for (uintptr_t p = 0x00663578; p < 0x0069c778; p += 914)
    if (BB_U32(p)) {
      BB_U32(p + 0x22) = 1;
      BB_U32(p + 0x26) = 1;
    }
  for (unsigned i = 0; i < 256; ++i) {
    long double angle =
        (long double)i * BB_DOUBLE(0x00482150) * BB_DOUBLE(0x00482158);
    /* The game's 53-bit final product determines the integer cache. Round
     * before truncating on hosts with wider C intermediates. */
    BB_U32(0x005d1150 + i * 4u) =
        (uint32_t)(int64_t)(double)(sinl(angle) * BB_DOUBLE(0x00482160));
    BB_U32(0x005d1558 + i * 4u) =
        (uint32_t)(int64_t)(double)(cosl(angle) * BB_DOUBLE(0x00482168));
  }
}

